CENSUS_HEADER = f"""# Classifier census

Generated by `tools/make_regime_ledger.py` from `reference/parameter_corpus.py`.
Do not edit; `make_regime_ledger.py --check` fails the build on a hand edit.

Each parameter's square `[-2, 2]^2` is cut into {2 ** CENSUS_RESOLUTION} boxes
a side and every box is classified by `reference/box_classifier.py`, with at most
{CENSUS_HORIZON} iterations per box. The certificates and what they are
allowed to mean are in `docs/three-valued-classifier.md`.

`UNKNOWN` is the column to read. It is the residual this programme reports
rather than shrinks, and it is the only column that carries no claim: a box
counted there is one the classifier refused to decide at this resolution, not
one that is known to meet the Julia set.

`IN` requires a trap, and a trap is a declared witness that is verified before
any verdict rests on it. A parameter with no trap is never counted `IN`, which
is correct where the interior is empty and is the fail-closed answer where a
parabolic basin has no strictly invariant box.
"""


def render_census() -> str:
    lines = [
        CENSUS_HEADER,
        "| key | `c` | regime | trap | OUT | IN | UNKNOWN |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in CORPUS:
        parameter = ComplexBox.singleton(row.c.re, row.c.im)
        trap, period = (None, 1)
        if row.key in TRAPS:
            corners, period = TRAPS[row.key]
            trap = ComplexBox.of(*corners)
            if not is_trap(trap, parameter, period):
                raise SystemExit(f"{row.key}: declared trap is not a trap of period {period}")
        counted = census(parameter, CENSUS_RESOLUTION, trap, period, horizon=CENSUS_HORIZON)
        witness = "--" if trap is None else f"`[{trap.re.lo}, {trap.re.hi}]^2`, period {period}"
        lines.append(
            f"| `{row.key}` | `{row.c}` | {row.regime.value} | {witness} | "
            f"{counted.out} | {counted.inside} | {counted.unknown} |"
        )
    for row in ac.ALGEBRAIC_CORPUS:
        algebraic_facts(row)
        trap, period = row.trap
        counted = census(row.handle.box, CENSUS_RESOLUTION, trap, period, horizon=CENSUS_HORIZON)
        lines.append(
            f"| `{row.key}` | root of `{poly_text(row.handle.polynomial)}` in its box | {ac.REGIME} | "
            f"`[{trap.re.lo}, {trap.re.hi}]^2`, period {period} | "
            f"{counted.out} | {counted.inside} | {counted.unknown} |"
        )
    lines.append("")
    lines.append(
        "The algebraic rows are classified with `c` ranging over the whole root box of "
        "`reference/algebraic_corpus.py`, so every verdict holds at the irrational centre."
    )
    lines.append("")
    return "\n".join(lines)


SURFACES = (
    (LEDGER, render_ledger),
    (CORPUS_JSON, render_corpus_json),
    (MOJO_CORPUS, render_mojo_corpus),
    (MOJO_ALGEBRAIC, render_mojo_algebraic),
    (CENSUS, render_census),
)


def main(argv: list[str]) -> int:
    check = "--check" in argv[1:]
    stale = []
    for path, render in SURFACES:
        content = render()
        if check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(content, encoding="utf-8")
    if check:
        if stale:
            print("STALE: " + ", ".join(stale) + " -- re-run tools/make_regime_ledger.py", file=sys.stderr)
            return 1
        print("OK: generated surfaces match reference/parameter_corpus.py")
        return 0
    print("wrote " + ", ".join(path.relative_to(ROOT).as_posix() for path, _ in SURFACES))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
