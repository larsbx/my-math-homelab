def mojo_point(z) -> str:
    return f"gaussian_q({z.re.numerator}, {z.re.denominator}, {z.im.numerator}, {z.im.denominator})"


MULTIPLIER_ALIAS = {
    "SUPERATTRACTING": "MULT_SUPERATTRACTING",
    "ATTRACTING": "MULT_ATTRACTING",
    "PARABOLIC": "MULT_PARABOLIC",
    "IRRATIONALLY_INDIFFERENT": "MULT_IRRATIONALLY_INDIFFERENT",
    "REPELLING": "MULT_REPELLING",
}


def mojo_expected_orbit(row: Parameter) -> tuple[str, int, int]:
    """The verdict the Mojo kernel must return at `MOJO_HORIZON`.

    A decided row decides at any budget that reaches it; an undecided row caps
    at every budget. Recomputing here rather than reusing the Python signature
    keeps the budget difference explicit instead of assumed.
    """
    orbit = critical_orbit(row.c, horizon=MOJO_HORIZON, bit_budget=1 << 30)
    if orbit.verdict is OrbitVerdict.ESCAPES:
        return "ORBIT_ESCAPES", orbit.escape_index, -1
    if orbit.verdict is OrbitVerdict.PREPERIODIC:
        return "ORBIT_PREPERIODIC", orbit.preperiod, orbit.period
    return "ORBIT_CAPPED", -1, -1


def render_mojo_corpus() -> str:
    zero = mojo_point(GQ.of(0))
    body: list[str] = []
    used: set[str] = {"ORBIT_CAPPED", "MULT_NONE"}
    for index, row in enumerate(CORPUS):
        kind, first, second = mojo_expected_orbit(row)
        cycle = row.cycle or ()
        multiplier_class = "MULT_NONE" if row.multiplier_class is None else MULTIPLIER_ALIAS[row.multiplier_class.value]
        used.add(kind)
        used.add(multiplier_class)
        body.append(f"    if index == {index}:")
        body.append(f'        return CorpusRow(')
        body.append(f'            "{row.key}",')
        body.append(f"            {mojo_point(row.c)},")
        body.append(f"            {len(cycle)},")
        body.append(f"            {mojo_point(cycle[0]) if len(cycle) > 0 else zero},")
        body.append(f"            {mojo_point(cycle[1]) if len(cycle) > 1 else zero},")
        body.append(f"            {multiplier_class},")
        body.append(f"            {kind},")
        body.append(f"            {first},")
        body.append(f"            {second},")
        body.append("        )")
    body.append(f'    return CorpusRow("", {zero}, 0, {zero}, {zero}, MULT_NONE, ORBIT_CAPPED, -1, -1)')
    body.append("")
    imports = "".join(f"\n    {name}," for name in sorted(used))
    header = MOJO_HEADER.format(size=len(CORPUS), horizon=MOJO_HORIZON, imports=imports)
    return "\n".join([header] + body)


