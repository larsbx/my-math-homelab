#!/usr/bin/env python3
"""Render the generated surfaces of the parameter corpus.

The corpus table in `reference/parameter_corpus.py` is the single source. This
script renders `docs/J1_regime_ledger.md` and `corpus.json` from it, filling
the verified columns by re-running `reference/julia_reference.py` on every row, so
a surface can only say what the oracle decided or what a row declared as an
unverified tag.

Usage:
    make_regime_ledger.py            write the surfaces
    make_regime_ledger.py --check    exit 1 if any surface is out of date

`--check` fails closed in the refuse-to-proceed direction: a hand-edited
surface fails the build rather than drifting away from the table.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

for _plane in ("vendor/python", "reference"):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / _plane))

from box_classifier import census, is_trap  # noqa: E402
from gaussian_q import GQ  # noqa: E402
from closed_interval import ComplexBox  # noqa: E402
from julia_reference import OrbitVerdict, classify_multiplier, critical_orbit, is_cycle, multiplier  # noqa: E402
from parameter_corpus import CORPUS, GATE, TRAPS, Parameter  # noqa: E402
import algebraic_corpus as ac  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "docs" / "J1_regime_ledger.md"
CORPUS_JSON = ROOT / "corpus.json"
MOJO_CORPUS = ROOT / "kernel" / "parameter_corpus.mojo"
MOJO_ALGEBRAIC = ROOT / "kernel" / "algebraic_corpus.mojo"
CENSUS = ROOT / "docs" / "classifier-census.md"

#: The census grid: `[-2, 2]^2` cut into `2^CENSUS_RESOLUTION` squared boxes,
#: each iterated at most `CENSUS_HORIZON` times. Both are small on purpose --
#: the census is a record of how the classifier behaves, not a rendering.
CENSUS_RESOLUTION = 4
CENSUS_HORIZON = 8

#: Step budget of the Mojo replay. Smaller than the Python horizon because the
#: replay recomputes earlier terms rather than storing them, and because a
#: capped row caps at any budget: the horizon changes how long an undecided
#: row runs, never what a decided row decides.
MOJO_HORIZON = 8

HEADER = """# J1 regime ledger

Generated by `tools/make_regime_ledger.py` from `reference/parameter_corpus.py`.
Do not edit; `make_regime_ledger.py --check` fails the build on a hand edit.

Two kinds of column appear below and they carry different authority.

- **Verified** columns are recomputed from the parameter by exact arithmetic
  on every render: the cycle witness, its multiplier class, and the
  critical-orbit verdict. A row cannot claim one of these and be wrong.
- **Tag** columns name an imported classical theorem. Each one was judged by
  the literature gate `docs/literature-gate-2026-09-19.md`, which located a
  source, recorded the qualification that is now part of the tag's meaning,
  and says what it did not do -- no theorem number was checked against a
  printed page. A gate verdict is not a proof, and no verified column below
  depends on a tag.

`J1 expects` says what the separator catalogue must do at this parameter if
`J1` is sound. It is the point of the corpus: the `STABILIZES` rows are the
confirmation cases that the parameter plane cannot supply. `UNDECIDED` records
an unresolved J1 obligation, not permanent undecidability or a claim that
local connectivity fails. The algebraic-multiplier import and its analytic
boundary are recorded in the notes rather than in the local-connectivity tag
column.

`CAPPED` is not a classification. Squaring doubles the coordinate bit length,
so an exactly iterated critical orbit that neither escapes nor repeats costs
`O(2^n)` bits at step `n`; every parabolic and irrationally indifferent row
exhausts its budget by construction, and reports which budget ran out.
"""

ROW_TEMPLATE = "| `{key}` | `{c}` | {regime} | {cycle} | {multiplier} | {orbit} | {lc} | {tag} | {j1} |"


def verified(row: Parameter) -> dict[str, str]:
    orbit = critical_orbit(row.c)
    if row.cycle is None:
        return {"cycle": "--", "multiplier": "--", "orbit": orbit.signature()}
    if not is_cycle(row.c, row.cycle):
        raise SystemExit(f"{row.key}: declared cycle is not a cycle of f_c")
    lam = multiplier(row.cycle)
    observed = classify_multiplier(lam)
    if observed is not row.multiplier_class:
        raise SystemExit(f"{row.key}: multiplier is {observed.value}, declared {row.multiplier_class.value}")
    if orbit.signature() != row.orbit_signature:
        raise SystemExit(f"{row.key}: critical orbit is {orbit.signature()}, declared {row.orbit_signature}")
    cycle = ", ".join(str(z) for z in row.cycle)
    return {
        "cycle": f"`{cycle}`",
        "multiplier": f"`{lam}` {observed.value}",
        "orbit": orbit.signature(),
    }


def render_ledger() -> str:
    lines = [
        HEADER,
        "| key | `c` | regime | cycle witness (verified) | multiplier (verified) | critical orbit (verified) | local connectivity | theorem tag (gated) | J1 expects |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in CORPUS:
        facts = verified(row)
        lines.append(
            ROW_TEMPLATE.format(
                key=row.key,
                c=row.c,
                regime=row.regime.value,
                cycle=facts["cycle"],
                multiplier=facts["multiplier"],
                orbit=facts["orbit"],
                lc=row.local_connectivity.value,
                tag="--" if row.theorem_tag is None else f"{row.theorem_tag} ({row.tag_status.value})",
                j1=row.j1_expectation.value,
            )
        )
    lines.append("")
    lines.append("## Notes")
    lines.append("")
    for row in CORPUS:
        lines.append(f"- **`{row.key}`** ({row.name}) -- {row.note}")
    lines.append("")
    lines += render_algebraic_ledger()
    return "\n".join(lines)


ALGEBRAIC_HEADER = """## Algebraic parameters

Generated from `reference/algebraic_corpus.py`. These parameters are
irrational, so `c` is a **root handle**: an integer polynomial and a rational
box isolating exactly one of its roots. The verified columns are recomputed
on every render, and a row that fails one is refused rather than rendered:

- **exact period** -- the polynomial divides `f_c^n(0)` and is coprime to
  `f_c^d(0)` for every proper divisor `d` of `n`, by exact integer algebra;
- **isolated** -- the Krawczyk image of the box lies strictly inside it, read
  through `KrawczykMooreUniqueness`; boxes on one polynomial are disjoint, and
  a declared conjugate has the conjugate box;
- **trap** -- the declared box is a trap of period `n` for every parameter in
  the root box (`reference/box_classifier.py`).

Which component a box sits in -- that the rays at the listed angles land at
its root -- is the import `RationalRayLanding`, named in the identification
column and not computed.
"""


def algebraic_facts(row: ac.AlgebraicParameter) -> None:
    problems = ac.row_errors(row, ac.ALGEBRAIC_CORPUS)
    if problems:
        raise SystemExit(f"{row.key}: " + "; ".join(problems))


def poly_text(p: tuple[int, ...]) -> str:
    terms = []
    for power in range(len(p) - 1, -1, -1):
        a = p[power]
        if a == 0:
            continue
        coefficient = "" if (a == 1 and power > 0) else str(a)
        variable = "" if power == 0 else ("c" if power == 1 else f"c^{power}")
        terms.append(coefficient + variable)
    return " + ".join(terms)


def box_text(box: ComplexBox) -> str:
    return f"[{box.re.lo}, {box.re.hi}] x [{box.im.lo}, {box.im.hi}]"


def render_algebraic_ledger() -> list[str]:
    lines = [
        ALGEBRAIC_HEADER,
        "| key | polynomial | period | exact period (verified) | isolated root (verified) | trap (verified) | identification (gated) | local connectivity | theorem tag (gated) | J1 expects |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in ac.ALGEBRAIC_CORPUS:
        algebraic_facts(row)
        trap, period = row.trap
        angles = ", ".join(str(a) for a in row.root_angles)
        lines.append(
            f"| `{row.key}` | `{poly_text(row.handle.polynomial)}` | {row.period} | yes | "
            f"`{box_text(row.handle.box)}` | `[{trap.re.lo}, {trap.re.hi}]^2`, period {period} | "
            f"{ac.IDENTIFICATION_TAG}: rays {angles} | TAGGED_LOCALLY_CONNECTED | "
            f"{ac.THEOREM_TAG} (ACCEPTED_WITH_QUALIFICATION) | {ac.J1_EXPECTATION} |"
        )
    lines.append("")
    for row in ac.ALGEBRAIC_CORPUS:
        conjugate = "" if row.conjugate_of is None else f" Conjugate of `{row.conjugate_of}`."
        lines.append(f"- **`{row.key}`** ({row.name}) -- {row.note}{conjugate}")
    lines.append("")
    return lines


def render_corpus_json() -> str:
    payload = []
    for row in CORPUS:
        facts = verified(row)
        payload.append(
            {
                "key": row.key,
                "name": row.name,
                "c": {"re": str(row.c.re), "im": str(row.c.im)},
                "regime": row.regime.value,
                "cycle": None if row.cycle is None else [{"re": str(z.re), "im": str(z.im)} for z in row.cycle],
                "multiplier_class": None if row.multiplier_class is None else row.multiplier_class.value,
                "critical_orbit": facts["orbit"],
                "local_connectivity": row.local_connectivity.value,
                "theorem_tag": row.theorem_tag,
                "theorem_tag_status": row.tag_status.value,
                "theorem_tag_gate": GATE,
                "j1_expectation": row.j1_expectation.value,
            }
        )
    algebraic = []
    for row in ac.ALGEBRAIC_CORPUS:
        algebraic_facts(row)
        box, (trap, period) = row.handle.box, row.trap
        algebraic.append(
            {
                "key": row.key,
                "name": row.name,
                "polynomial": list(row.handle.polynomial),
                "box": {"re": [str(box.re.lo), str(box.re.hi)], "im": [str(box.im.lo), str(box.im.hi)]},
                "period": row.period,
                "regime": ac.REGIME,
                "multiplier_class": ac.MULTIPLIER_CLASS,
                "trap": {"re": [str(trap.re.lo), str(trap.re.hi)], "im": [str(trap.im.lo), str(trap.im.hi)], "period": period},
                "conjugate_of": row.conjugate_of,
                "root_angles": [str(a) for a in row.root_angles],
                "identification_tag": ac.IDENTIFICATION_TAG,
                "local_connectivity": "TAGGED_LOCALLY_CONNECTED",
                "theorem_tag": ac.THEOREM_TAG,
                "theorem_tag_status": "ACCEPTED_WITH_QUALIFICATION",
                "theorem_tag_gate": GATE,
                "j1_expectation": ac.J1_EXPECTATION,
            }
        )
    return json.dumps({"corpus": payload, "algebraic": algebraic}, indent=2, sort_keys=False) + "\n"


